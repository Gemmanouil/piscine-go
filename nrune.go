package piscine

// NRune επιστρέφει τον χαρακτήρα στη θέση n (ξεκινώντας από 1) της συμβολοσειράς s
// Αν η θέση δεν υπάρχει, επιστρέφει 0
func NRune(s string, n int) rune {
	if n < 1 {
		return 0 // δεν υπάρχουν χαρακτήρες πριν από τη θέση 1
	}

	count := 1 // μετρητής θέσης χαρακτήρων
	for _, r := range s {
		if count == n {
			return r // επιστρέφουμε τον χαρακτήρα στη θέση n
		}
		count++
	}

	return 0 // αν δεν βρέθηκε η θέση n, επιστρέφουμε 0
}
