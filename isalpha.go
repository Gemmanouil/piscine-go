package piscine

// IsAlpha επιστρέφει true αν η συμβολοσειρά είναι κενή ή περιέχει μόνο αλφαριθμητικούς χαρακτήρες
func IsAlpha(s string) bool {
	for _, r := range s {
		if !(r >= 'A' && r <= 'Z') && !(r >= 'a' && r <= 'z') && !(r >= '0' && r <= '9') {
			return false // αν βρούμε μη αλφαριθμητικό χαρακτήρα, επιστρέφουμε false
		}
	}
	return true // όλοι οι χαρακτήρες ήταν αλφαριθμητικοί ή η συμβολοσειρά ήταν κενή
}
