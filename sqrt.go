package piscine

// Sqrt επιστρέφει την τετραγωνική ρίζα του nb αν είναι ακέραιος αριθμός
// Αν δεν είναι ακέραιος ή αν το nb είναι αρνητικό, επιστρέφει 0
func Sqrt(nb int) int {
	if nb < 0 {
		return 0 // αρνητικός αριθμός δεν έχει πραγματική τετραγωνική ρίζα
	}

	// Δοκιμάζουμε όλους τους αριθμούς από 1 μέχρι nb
	i := 1
	for i*i <= nb {
		if i*i == nb {
			return i // βρήκαμε την ακέραια τετραγωνική ρίζα
		}
		i++
	}

	return 0 // δεν υπάρχει ακέραια τετραγωνική ρίζα
}
